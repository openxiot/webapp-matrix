/**
 * 一个对象在 3D 模型里的位置。**空间和设备共用**。
 *
 * - `SpaceEntity.anchor` —— 这个区域在模型上的位置
 * - `DeviceEntity.anchor` —— 这台设备在模型上的位置
 *
 * 设备没有自己的锚点时，落到它所属空间的锚点上（回退链见
 * `pages/main/project/3d/anchor/project.3d.anchor.ts` 的 `resolveAnchor`）。所以一台设备
 * 不标也能在模型上出现，标了则精确到点 —— 不用给一个区域里的 50 台传感器挨个点 50 次。
 *
 * 坐标为**模型根节点的局部坐标**，不是世界坐标。今天 `gltf.scene` 没有变换，两者相同；
 * 存局部坐标是为了将来给根节点加居中/缩放变换时，全部锚点不会一起作废。
 */
export class ModelAnchor {
  /** 模型标识，如 `001` */
  model: string = '';

  /**
   * 模型内容版本。同一个 URL 重新导出后坐标就不再可信 —— 靠它判定失效。
   * 不符**一律不渲染**：宁可缺，不可错（画到错误位置比不画难查得多）。
   */
  rev: string = '';

  /** 模型根节点的局部坐标 */
  x: number = 0;
  y: number = 0;
  z: number = 0;

  /** 绕 Y 轴的偏航角（弧度）。路灯、摄像头这类有朝向的对象用；本期不用，先留着。 */
  ry?: number;
}
